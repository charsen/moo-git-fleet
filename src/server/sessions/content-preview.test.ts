import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  isSystemNoise,
  normalizeSessionDisplayText,
  normalizeSessionTitle,
  previewSessionContent,
} from './content-preview.js';

const temporaryDirectories: string[] = [];

afterEach(async () => {
  await Promise.all(temporaryDirectories.splice(0).map((directory) => rm(directory, { recursive: true, force: true })));
});

describe('isSystemNoise', () => {
  it('识别两个 provider 注入的伪标签', () => {
    expect(isSystemNoise('<task-notification> agent finished </task-notification>')).toBe(true);
    expect(isSystemNoise('<system-reminder>记得写测试</system-reminder>')).toBe(true);
    expect(isSystemNoise('<environment_context>\n  <cwd>/work</cwd>')).toBe(true);
    expect(isSystemNoise('<codex_internal_context source="goal">')).toBe(true);
    expect(isSystemNoise('  <local-command-stdout>ok</local-command-stdout>')).toBe(true);
    expect(isSystemNoise('Caveat: The messages below were generated by the user')).toBe(true);
  });

  it('不误伤真人写的内容，包括普通 HTML', () => {
    expect(isSystemNoise('帮我看下这个 bug')).toBe(false);
    expect(isSystemNoise('<div>为什么这个标签没渲染</div>')).toBe(false);
    expect(isSystemNoise('<?php echo 1; ?>')).toBe(false);
    expect(isSystemNoise('a < b 的判断写错了')).toBe(false);
  });
});

describe('previewSessionContent', () => {
  it('跳过注入消息，只留真实对话', async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), 'fleet-preview-'));
    temporaryDirectories.push(root);
    const filePath = path.join(root, 'session.jsonl');
    const lines = [
      { type: 'user', timestamp: '2026-07-30T10:00:00.000Z', message: { role: 'user', content: '<system-reminder>忽略我</system-reminder>' } },
      { type: 'user', timestamp: '2026-07-30T10:01:00.000Z', message: { role: 'user', content: '帮我改一下同步逻辑' } },
      { type: 'assistant', timestamp: '2026-07-30T10:02:00.000Z', message: { role: 'assistant', content: '好的，我先看代码' } },
    ];
    await writeFile(filePath, `${lines.map((line) => JSON.stringify(line)).join('\n')}\n`);

    const preview = await previewSessionContent(filePath);

    expect(preview.items.map((item) => item.text)).toEqual(['帮我改一下同步逻辑', '好的，我先看代码']);
    expect(preview.totalMessages).toBe(2);
  });

  it('隐藏图片附件的本机路径，只保留友好提示与正文', async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), 'fleet-preview-image-'));
    temporaryDirectories.push(root);
    const filePath = path.join(root, 'session.jsonl');
    const content = '<image name=[Image #1] path="/private/tmp/clipboard-secret.png"> [Image #1] 这个按钮怎么还是两行？';
    await writeFile(filePath, `${JSON.stringify({ type: 'user', message: { role: 'user', content } })}\n`);

    const preview = await previewSessionContent(filePath);

    expect(preview.items[0]?.text).toBe('（图片附件） 这个按钮怎么还是两行？');
    expect(preview.items[0]?.text).not.toContain('/private/tmp');
  });
});

describe('session text normalization', () => {
  it('标题去掉图片标记，只有附件时不产生伪标题', () => {
    expect(normalizeSessionTitle('<image name=[Image #1] path="/tmp/private.png"> [Image #1] 修复这个提示')).toBe('修复这个提示');
    expect(normalizeSessionTitle('<image name=[Image #1] path="/tmp/private.png"> [Image #1]')).toBeNull();
    expect(normalizeSessionDisplayText('[Image #2] 看下这里')).toBe('（图片附件） 看下这里');
  });
});
